// Geometry guides and reproducible mobile preparation. No procedural painting.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const review = path.join(root, 'docs/reference/interface-review/v20-dig-blocks-painted');
const source = path.join(review, 'source');
const runtime = path.join(root, 'assets/previews/dig-blocks');
const height = .3133333333333333;
const footprint = .74;
const scale = 840/(footprint*256);
const rise = height*256*.6123724356957945*scale;
const vertices = {a:[512,170],b:[932,380],c:[512,590],d:[92,380],e:[932,380+rise],f:[512,590+rise],g:[92,380+rise]};
const faces = [['b','e','f','c'],['c','f','g','d'],['a','b','c','d']];
async function guides() {
  fs.mkdirSync(source,{recursive:true});
  const colors = ['#202a3e','#29364c','#3c4963'];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024">${faces.map((face,i)=>`<polygon points="${face.map(k=>vertices[k].join(',')).join(' ')}" fill="${colors[i]}" stroke="#bb76d5" stroke-width="2"/>`).join('')}</svg>`;
  fs.writeFileSync(path.join(source,'approved-guide.svg'),svg);
  await sharp(Buffer.from(svg)).png().toFile(path.join(source,'approved-guide.png'));
  await sharp(path.join(root,'artifacts/dig-blocks/1280x720.png')).extract({left:535,top:310,width:515,height:280}).png().toFile(path.join(source,'dungeon-style.png'));
  fs.writeFileSync(path.join(source,'geometry.json'),JSON.stringify({height,footprint,scale,vertices,faces},null,2)+'\n');
}
async function prepare() {
  fs.mkdirSync(runtime,{recursive:true});
  const record={geometry:{height,footprint},variants:[]};
  const registration=JSON.parse(fs.readFileSync(path.join(source,'registration.json'),'utf8'));
  const entries=[];
  for (const {name,vertices:painted} of registration.variants) {
    const original=path.join(source,name+'.png');
    if (!fs.existsSync(original)) throw new Error(`Missing painted source: ${original}`);
    const input=await sharp(original).metadata();
    const output=path.join(runtime,name+'.png');
    await sharp(original).resize({width:256}).png().toFile(output);
    const info=await sharp(output).metadata();
    const uvs=faces.map(face=>face.map(k=>[painted[k][0]/input.width,painted[k][1]/input.height]));
    for (const face of uvs) for (const uv of face) if(uv.some(n=>!Number.isFinite(n)||n<0||n>1)) throw new Error('Invalid paint registration');
    entries.push(`{\"texture\":preload(\"res://assets/previews/dig-blocks/${name}.png\"),\"uvs\":[${uvs.map(face=>`PackedVector2Array([${face.map(p=>`Vector2(${p.join(',')})`).join(',')}])`).join(',')}]}`);
    record.variants.push({name,source:path.relative(root,original).replaceAll('\\','/'),sha256:crypto.createHash('sha256').update(fs.readFileSync(original)).digest('hex'),size:[info.width,info.height],bytes:fs.statSync(output).size,rgbaBytes:info.width*info.height*4,uvs});
  }
  fs.writeFileSync(path.join(runtime,'paint.gd'),'extends RefCounted\n# Generated by tools/prepare_dig_block_art.cjs. Never alter approved geometry to fit paint.\nstatic func variants() -> Array:\n\treturn [\n'+entries.map(entry=>'\t\t'+entry).join(',\n')+'\n\t]\n');
  fs.writeFileSync(path.join(review,'preparation.json'),JSON.stringify(record,null,2)+'\n');
  console.log(JSON.stringify(record));
}
(process.argv.includes('--guides')?guides():prepare()).catch(error=>{console.error(error);process.exitCode=1;});
